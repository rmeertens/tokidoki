#!/usr/bin/env node
// Writes vocab-fill-data.js, the fill-in-the-blank questions of the JLPT
// Questions page (vocab-questions.html): the hand-checked ones in
// scripts/vocab_fill_reviewed.json, built by scripts/vocab_questions.mjs.
//
//   node scripts/build_vocab_fill.mjs
//
// To add questions, look at more candidates (buildFill(level) there), check
// that only the answer fits, and add the word to the reviewed list.
import { writeFileSync } from "node:fs";
import { LEVELS, reviewedFill } from "./vocab_questions.mjs";

export function fillData() {
  const out = {};
  for (const level of LEVELS) {
    out[level] = reviewedFill(level).map((q) => ({ w: q.word, k: q.kana, en: q.en, b: q.before, a: q.after, c: q.choices }));
  }
  return out;
}

export function fillFile() {
  const levels = Object.entries(fillData()).map(([level, qs]) =>
    `    ${level}: [\n${qs.map((q) => `      ${JSON.stringify(q)},`).join("\n")}\n    ],`).join("\n");
  return `(function (global) {
  'use strict';

  // Generated by scripts/build_vocab_fill.mjs — do not hand-edit.
  //
  // Fill-in-the-blank questions (文脈規定) for the JLPT Questions page, per
  // level: w / k the word and its reading, en the sentence in English,
  // b / a the sentence before and after the blank (furigana as {漢字|かな}),
  // c the choices [markup, word, reading, meaning], the answer first. The
  // sentences are Tokidoki's own (scripts/guess_examples.tsv).

  global.VOCAB_FILL = {
${levels}
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../vocab-fill-data.js", import.meta.url), fillFile());
  for (const [level, qs] of Object.entries(fillData())) console.log(`${level}: ${qs.length} questions`);
}
